// Generates warm, Chop-voiced notification text via Groq (free tier).
// Every function has a plain fallback, so notifications still work if the AI is down.

const MODELS = ["openai/gpt-oss-20b", "llama-3.1-8b-instant", "openai/gpt-oss-120b"];

const PERSONA =
  "\u0422\u044b \u2014 \u0427\u043e\u043f, \u043c\u0438\u043b\u044b\u0439 \u0447\u0451\u0440\u043d\u044b\u0439 \u043a\u043e\u0442-\u043f\u043e\u043c\u043e\u0449\u043d\u0438\u043a \u0432 \u043f\u0440\u0438\u043b\u043e\u0436\u0435\u043d\u0438\u0438-\u043e\u0440\u0433\u0430\u043d\u0430\u0439\u0437\u0435\u0440\u0435. " +
  "\u041f\u0438\u0448\u0438 \u0442\u0435\u043f\u043b\u043e, \u043f\u043e-\u0434\u043e\u0431\u0440\u043e\u043c\u0443, \u043a\u043e\u0440\u043e\u0442\u043a\u043e, \u043d\u0430 \u00ab\u0442\u044b\u00bb, \u0441 1-2 \u044d\u043c\u043e\u0434\u0437\u0438. " +
  "\u0412\u044b\u0434\u0430\u0432\u0430\u0439 \u0422\u041e\u041b\u042c\u041a\u041e \u0441\u0430\u043c \u0442\u0435\u043a\u0441\u0442 \u0441\u043e\u043e\u0431\u0449\u0435\u043d\u0438\u044f \u2014 \u0431\u0435\u0437 \u043a\u0430\u0432\u044b\u0447\u0435\u043a, \u0431\u0435\u0437 \u043f\u043e\u044f\u0441\u043d\u0435\u043d\u0438\u0439.";

async function gen(prompt, fallback) {
  const apiKey = process.env.GROQ_API_KEY;
  if (!apiKey) return fallback;
  try {
    let lastErr = "";
    for (const model of MODELS) {
      const res = await fetch("https://api.groq.com/openai/v1/chat/completions", {
        method: "POST",
        headers: { "Content-Type": "application/json", Authorization: `Bearer ${apiKey}` },
        body: JSON.stringify({
          model,
          temperature: 0.7,
          max_tokens: 220,
          messages: [
            { role: "system", content: PERSONA },
            { role: "user", content: prompt },
          ],
        }),
      });
      if (res.ok) {
        const d = await res.json();
        const t = (d.choices?.[0]?.message?.content || "").trim();
        return t || fallback;
      }
      lastErr = String(res.status);
      if (res.status !== 404 && res.status !== 400) break;
    }
    console.error("chopNotify gen failed:", lastErr);
    return fallback;
  } catch (e) {
    console.error("chopNotify gen error:", e.message);
    return fallback;
  }
}

export function warmReminder(text) {
  return gen(
    `\u041f\u043e\u0440\u0430 \u043d\u0430\u043f\u043e\u043c\u043d\u0438\u0442\u044c \u043f\u043e\u043b\u044c\u0437\u043e\u0432\u0430\u0442\u0435\u043b\u044e \u043e\u0431 \u044d\u0442\u043e\u043c \u0434\u0435\u043b\u0435, \u0442\u0435\u043f\u043b\u043e \u0438 \u043a\u043e\u0440\u043e\u0442\u043a\u043e (1 \u043f\u0440\u0435\u0434\u043b\u043e\u0436\u0435\u043d\u0438\u0435): "${text}"`,
    `\u23f0 \u0427\u043e\u043f \u043d\u0430\u043f\u043e\u043c\u0438\u043d\u0430\u0435\u0442: ${text} \ud83d\udc3e`
  );
}

